// compile-time FNV-1a hash function for color name lookup (case insensitive)
static constexpr uint32_t HashColorName(std::string_view str)
{
    uint32_t hash = 2166136261u;
    for (const auto c : str)
    {
        // convert to lowercase during hashing
        const char ch = (c >= 'A' && c <= 'Z') ? (c + 32) : c;
        hash ^= static_cast<uint32_t>(ch);
        hash *= 16777619u;
    }
    return hash;
}

