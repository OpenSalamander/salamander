bool LookupX11Color(std::string_view name, COLORREF& outColor)
{
#ifdef _DEBUG
    // diagnostics: ensure that there are no hash collisions!
    std::call_once(g_hashCollisionCheckFlag, []() {
        // check each pair of hashes for uniqueness
        for (auto i = std::begin(g_X11Colors); i != std::end(g_X11Colors); i++)
        {
            for (auto j = i + 1; j != std::end(g_X11Colors); j++)
            {
                assert(i->hash != j->hash && "Hash collision detected!");
            }
        } });
#endif // _DEBUG

    // compute hash of input name (case-insensitive)
    const auto hash = HashColorName(name);

    const auto it = std::find_if(std::begin(g_X11Colors), std::end(g_X11Colors),
                                 [hash](const X11ColorEntry& entry)
                                 { return entry.hash == hash; });

    if (it == std::end(g_X11Colors))
        return false;

    outColor = it->rgb;
    return true;
}
